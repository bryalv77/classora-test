import type { OpenAPIV3 } from 'openapi-types';
import { parse } from 'yaml';
import { derefIn } from './deref.ts';

export function generateContract(contractText: string): string {
  const spec = parse(contractText) as OpenAPIV3.Document; // the one assertion: `parse` returns `any`

  const params = Object.fromEntries(
    (spec.paths['/api/v1/tickets']?.get?.parameters ?? []).map((ref) => {
      const param = derefIn(spec, ref);
      if (!param.schema) throw new Error(`openapi-rest.yml: the parameter ${param.name} has no schema`);
      const { default: byDefault, minimum, maximum, maxLength, enum: values } = derefIn(spec, param.schema);
      const rules = { default: byDefault, minimum, maximum, maxLength, enum: values };
      return [param.name, Object.fromEntries(Object.entries(rules).filter(([, v]) => v !== undefined))];
    }),
  );

  const enums = Object.fromEntries(
    Object.entries(spec.components?.schemas ?? {})
      .map(([name, schema]) => [name, derefIn(spec, schema).enum] as const)
      .filter(([, values]) => values !== undefined),
  );

  return `// AUTO-GENERATED by \`pnpm generate\` from openapi-rest.yml. Do not edit by hand.

// Query parameters of GET /api/v1/tickets: defaults and limits.
export const listTicketsParams = ${JSON.stringify(params, null, 2)} as const;

// Values of every enum schema of the contract.
export const contractEnums = ${JSON.stringify(enums, null, 2)} as const;
`;
}
